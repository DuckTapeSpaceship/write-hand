// Generates tests/fixtures/strokes/sample.json: deterministic "handwriting"
// skeletons (Catmull-Rom through control points, a little jitter) in the same
// format the lab's stroke recorder saves. Font units, baseline 0, x-height 420.
import { writeFileSync, mkdirSync } from 'node:fs'

let seed = 7
const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647) - 0.5

function catmull(ctrl, step = 12) {
  if (ctrl.length === 1) return [ctrl[0]]
  const pts = [ctrl[0], ...ctrl, ctrl[ctrl.length - 1]]
  const out = []
  for (let i = 1; i < pts.length - 2; i++) {
    const [p0, p1, p2, p3] = [pts[i - 1], pts[i], pts[i + 1], pts[i + 2]]
    const segLen = Math.hypot(p2[0] - p1[0], p2[1] - p1[1])
    const n = Math.max(2, Math.ceil(segLen / step))
    for (let k = 0; k < n; k++) {
      const t = k / n, t2 = t * t, t3 = t2 * t
      const f = (a, b, c, d) => 0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3)
      out.push([f(p0[0], p1[0], p2[0], p3[0]), f(p0[1], p1[1], p2[1], p3[1])])
    }
  }
  out.push(ctrl[ctrl.length - 1])
  return out
}

function stroke(ctrl) {
  const pts = []
  catmull(ctrl).forEach(([x, y], i) => {
    pts.push(+(x + rand() * 2).toFixed(1), +(y + rand() * 2).toFixed(1), 0.5, i * 8)
  })
  return { pts, pointer: 'mouse' }
}

